// Commit 5: the app icons, favicons, link preview and manifest colours in the
// "Scoreboard" identity, all generated from ONE source.
//
//   node tests/brand.test.js
//
// - scripts/brand/brand.html is the only source; make-icons.ps1 renders it;
// - its colours are still the theme.css tokens (navy, navy-hover, the dark
//   navy-ink, on-navy); no gradient, no emoji, no third-party font host; the
//   wordmark in the number face, from public/vendor/fonts;
// - every generated PNG exists at its size; the app icons and og.png are
//   opaque (iOS and WhatsApp paint transparency black); favicon.svg is the
//   generated wrapper; the manifest is navy and points at real files.
// No dependencies.

import { readFileSync, existsSync, readdirSync } from 'node:fs';

let passed = 0;
const failures = [];
const check = (name, ok, detail) => { if (ok) passed++; else failures.push(detail ? `${name}\n      ${detail}` : name); };
const read = (p) => readFileSync(new URL('../' + p, import.meta.url), 'utf8');
const bytes = (p) => readFileSync(new URL('../' + p, import.meta.url));

// ── One source ──
check('scripts/brand holds one source: brand.html', JSON.stringify(readdirSync(new URL('../scripts/brand/', import.meta.url))) === '["brand.html"]');
const mk = read('scripts/make-icons.ps1');
check('make-icons.ps1 renders brand.html, every view', /brand\\brand\.html/.test(mk) && ['icon', 'maskable', 'round', 'og'].every((v) => new RegExp(`Shoot '${v}'`).test(mk)));
check('make-icons.ps1 stops if the fonts did not load', /function AssertFonts/.test(mk) && /fonts-ready/.test(mk) && /^\s*AssertFonts\s*$/m.test(mk));

// ── The source follows the tokens ──
const brand = read('scripts/brand/brand.html');
const css = read('public/theme.css');
const tok = (block, name) => {
  const i = css.indexOf(block + '{'); const body = css.slice(i, css.indexOf('}', i));
  return ((new RegExp('--' + name + ':\\s*(#[0-9A-Fa-f]{6})').exec(body)) || [])[1];
};
const want = { navy: tok(':root', 'navy'), band: tok(':root', 'navy-hover'), scout: tok('[data-theme="dark"]', 'navy-ink'), mind: tok(':root', 'on-navy') };
const got = Object.fromEntries((/:root\{([^}]*)\}/.exec(brand) || ['', ''])[1].split(';').filter(Boolean).map((d) => d.replace('--', '').split(':')));
check('brand.html colours are the theme.css tokens', Object.keys(want).every((k) => String(got[k]).toUpperCase() === String(want[k]).toUpperCase()),
  JSON.stringify(got) + ' vs ' + JSON.stringify(want));
const style = (/<style>([\s\S]*?)<\/style>/.exec(brand) || ['', ''])[1];
const literals = [...style.replace(/:root\{[^}]*\}/, '').matchAll(/#[0-9A-Fa-f]{3,8}\b|rgba?\(/g)].map((m) => m[0]);
check('no colour outside the token block', literals.length === 0, literals.join(' '));
check('no gradient', !/gradient/i.test(brand.replace(/<!--[\s\S]*?-->/g, '')));
check('no emoji or dingbat', !/[⌀-⏿■-◿☀-➿⬀-⯿️]|[\uD83C-\uDBFF][\uDC00-\uDFFF]/u.test(brand));
check('fonts from public/vendor, never a third-party host', !/https?:\/\//.test(style) && /vendor\/fonts\/barlow-condensed-normal-700-latin\.woff2/.test(brand) && /vendor\/fonts\/dm-sans-normal-300-700-latin\.woff2/.test(brand));
check('the wordmark and the monogram are in the number face', /\.num\{font-family:'Barlow Condensed'/.test(brand) && /class="word num"/.test(brand) && /class="mono num"/.test(brand));
check('the preview carries no number (CLAUDE.md rule 22)', !/\d/.test((/view === 'og'[\s\S]*?: mono;/.exec(brand) || [''])[0].replace(/<[^>]*>/g, '')));

// ── What it generated ──
function png(p) {
  const b = bytes(p);
  if (b.readUInt32BE(0) !== 0x89504e47) return null;
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20), colourType: b[25] };   // 2 = RGB (opaque), 6 = RGBA
}
const SIZES = { 'public/icon-192.png': 192, 'public/icon-512.png': 512, 'public/icon-maskable-192.png': 192, 'public/icon-maskable-512.png': 512, 'public/apple-touch-icon.png': 180 };
for (const [p, s] of Object.entries(SIZES)) {
  const i = existsSync(new URL('../' + p, import.meta.url)) ? png(p) : null;
  check(`${p}: ${s}x${s}, opaque`, !!i && i.w === s && i.h === s && i.colourType === 2, i && JSON.stringify(i));
}
const og = png('public/og.png');
check('public/og.png: 1200x630, opaque', !!og && og.w === 1200 && og.h === 630 && og.colourType === 2, og && JSON.stringify(og));
const ico = bytes('public/favicon.ico');
check('favicon.ico: 16, 32 and 48', ico.readUInt16BE(0) === 0 && ico.readUInt16LE(4) === 3 && [0, 1, 2].map((i) => ico[6 + 16 * i]).join() === '16,32,48');
const fsvg = read('public/favicon.svg');
check('favicon.svg is the generated wrapper (the real number face)', /Generated by scripts\/make-icons\.ps1/.test(fsvg) && /href="data:image\/png;base64,/.test(fsvg));

// Link previews are cached per image URL: every page names the same versioned one.
const ogUrls = ['index', 'about', 'auth', 'community', 'privacy', 'terms'].map((p) => (/<meta property="og:image" content="([^"]+)">/.exec(read(`public/${p}.html`)) || [])[1]);
check('every page points og:image at the same versioned og.png (bump ?v= when the image changes)',
  new Set(ogUrls).size === 1 && /^https:\/\/scoutmind\.app\/og\.png\?v=\w+$/.test(ogUrls[0]), ogUrls.join(' '));

// ── Manifest ──
const mf = JSON.parse(read('public/manifest.json'));
check('manifest theme and splash are the navy token', mf.theme_color === want.navy && mf.background_color === want.navy);
check('every manifest icon file exists', mf.icons.every((i) => existsSync(new URL('../public' + i.src, import.meta.url))));
const sw = read('public/sw.js');
check('the service worker precaches every manifest icon', mf.icons.every((i) => sw.includes(`'${i.src}'`)));

for (const f of failures) console.log(`  FAIL  ${f}`);
console.log(`\n${passed} passed, ${failures.length} failed`);
process.exit(failures.length ? 1 : 0);
