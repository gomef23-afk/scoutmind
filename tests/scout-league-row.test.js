// The Scout tab's league row (25 Nov 2026).
//
//   node tests/scout-league-row.test.js
//
// With nine playable leagues the tabs overflowed and Rankings / My history
// went off screen on a laptop. The rule now:
// - a fixed row from the config (api/_lib/leagues.js scoutRow → LeagueNames):
//   Série A, Premier League, La Liga, Serie A, Bundesliga, Ligue 1, then More;
// - every other playable league with a round is under More (my main club's
//   league first, then alphabetical); a chosen one is named on the More tab,
//   and choosing a fixed league puts "More" back;
// - a fan whose main club plays in a More league opens Scout on it;
// - the views (Round · Rankings · My history) are their own row below,
//   which never scrolls; on a laptop the league row wraps instead of
//   scrolling, and the More menu sits outside the scrolling row;
// - nothing in the page names a league: the split comes from the config.
// No dependencies.

import { readFileSync } from 'node:fs';
import vm from 'node:vm';

let passed = 0;
const failures = [];
const check = (name, ok, detail) => { if (ok) passed++; else failures.push(detail ? `${name}\n      ${detail}` : name); };
const eq = (name, got, want) => check(name, JSON.stringify(got) === JSON.stringify(want), `got ${JSON.stringify(got)}\n      want ${JSON.stringify(want)}`);
const read = (p) => readFileSync(new URL('../' + p, import.meta.url), 'utf8');

// ── 1. The config ──
const { LEAGUES } = await import('../api/_lib/leagues.js');
const row = LEAGUES.filter((l) => l.scoutRow).sort((a, b) => a.scoutRow - b.scoutRow);
eq('the fixed row, in order (decision of 25 Nov 2026)', row.map((l) => l.slug), ['serie_a', 'premier_league', 'la_liga', 'serie_a_it', 'bundesliga', 'ligue_1']);
eq('places 1..6, each once', row.map((l) => l.scoutRow), [1, 2, 3, 4, 5, 6]);
check('only playable leagues carry a place (and never a cup)', LEAGUES.every((l) => !l.scoutRow || (l.playable && l.type === 'league')));
check('a playable league without a place goes under More (today Argentina, the Championship, the Primeira Liga)',
  ['argentina', 'championship', 'primeira_liga'].every((s) => LEAGUES.find((l) => l.slug === s && l.playable && !l.scoutRow)));

const ctx = {}; ctx.window = ctx; vm.createContext(ctx);
vm.runInContext(read('public/league-names.js'), ctx);
const LN = ctx.LeagueNames;
eq('league-names.js carries the places (generated by sync-leagues)', LN.LEAGUES.filter((l) => l.scoutRow).sort((a, b) => a.scoutRow - b.scoutRow).map((l) => [l.slug, l.scoutRow]),
  row.map((l) => [l.slug, l.scoutRow]));
eq('LeagueNames.scoutRow: by slug, by row; null for a More league or an unknown one',
  [LN.scoutRow('serie_a'), LN.scoutRow({ slug: 'ligue_1' }), LN.scoutRow('championship'), LN.scoutRow('nope'), LN.scoutRow(null)], [1, 6, null, null, null]);

// ── 2. The page's split, run on rounds of nine leagues ──
const idx = read('public/index.html');
const fnSrc = (name) => (new RegExp(`function ${name}\\([^)]*\\)\\{[\\s\\S]*?\\n\\}`).exec(idx) || [''])[0];
const split = fnSrc('sgLeagueRow');
check('sgLeagueRow exists', split.length > 0);
const slugs = ['championship', 'ligue_1', 'serie_a_it', 'argentina', 'premier_league', 'primeira_liga', 'bundesliga', 'la_liga', 'serie_a'];
const rounds = slugs.map((s, i) => ({ league_id: 100 + i, leagues: { slug: s } }));
function runRow(mainLeague) {
  const sb = { LeagueNames: LN, CLUB_DATA: new Map([[7, { id: 7, league: mainLeague }]]), mainClubId: () => 7 };
  vm.createContext(sb);
  vm.runInContext(`function sgSlugOf(r){ return r&&r.leagues&&r.leagues.slug||''; }\n${split}`, sb);
  const r = sb.sgLeagueRow(rounds);
  return { main: r.main.map((x) => x.leagues.slug), more: r.more.map((x) => x.leagues.slug) };
}
eq('fixed row in the config\'s order; More: the rest, alphabetical by label', runRow('serie_a'),
  { main: ['serie_a', 'premier_league', 'la_liga', 'serie_a_it', 'bundesliga', 'ligue_1'], more: ['championship', 'argentina', 'primeira_liga'] });
eq('…my main club\'s More league first', runRow('primeira_liga').more, ['primeira_liga', 'championship', 'argentina']);
eq('…the fixed row never moves for a fan', runRow('primeira_liga').main, ['serie_a', 'premier_league', 'la_liga', 'serie_a_it', 'bundesliga', 'ligue_1']);

const def = fnSrc('sgDefaultLeague');
check('a fan opens Scout on their main club\'s league, a More league included', /const mine=main&&leagues\.find\(r=>sgSlugOf\(r\)===main\.league\);/.test(def) && /return \(mine\|\|leagues\[0\]\)\.league_id;/.test(def));
check('sgLeagues returns the row\'s order (fixed, then More), no main-club-first sort of its own', /const row=sgLeagueRow\(\[\.\.\.seen\.values\(\)\]\);\s*return row\.main\.concat\(row\.more\);/.test(fnSrc('sgLeagues')));
check('renderScout chooses a league for every view (the row always shows one)', /\/\/ The league row always shows one league as chosen, whatever the view\.\s*if\(SG\.leagueId==null\|\|!sgLeagues\(\)\.some\(r=>r\.league_id===SG\.leagueId\)\) SG\.leagueId=sgDefaultLeague\(\);\s*if\(SG\.view==='league'\)\{/.test(idx));

// ── 3. The More tab and the views ──
const tabs = fnSrc('sgTabs');
check('More names the chosen More league, else says More, with a chevron icon (no dingbat)',
  /sanitize\(chosen\?sgLeagueName\(chosen\):t\('sg\.tab\.more'\)\)/.test(tabs) && /Icons\.svg\('chevronDown',14\)/.test(tabs) && !/[▴-▿]/.test(tabs));
check('More is a menu button (aria-haspopup, aria-expanded, aria-controls) and its items are radio items', /aria-haspopup="menu" aria-expanded="false" aria-controls="sg-more-menu"/.test(tabs)
  && /role="menuitemradio" aria-checked="'\+\(r\.league_id===SG\.leagueId\)\+'"/.test(tabs));
check('no More tab when there is nothing under it', /if\(row\.more\.length\)\{/.test(tabs));
check('the views row: Round · Rankings · My history (· Recaps since R-2), in its own element', /views\.innerHTML=v\('league','sg\.tab\.round','sgShowRound'\)\+v\('rankings','sg\.tab\.rankings','sgShowRankings'\)\+v\('history','sg\.tab\.history','sgShowHistory'\)\s*\+v\('recaps','sg\.tab\.recaps','sgShowRecaps'\);/.test(tabs));
check('nothing in the row code names a league', !/'(serie_a|premier_league|la_liga|serie_a_it|bundesliga|ligue_1|argentina|championship|primeira_liga)'/.test(tabs + split + def));
const pick = fnSrc('sgPickLeague');
check('choosing a league: Rankings stay Rankings (for it), any other view opens its round', /SG\.leagueId=id; SG\.roundId=sgDefaultRound\(id\);\s*if\(SG\.view!=='rankings'\) SG\.view='league';/.test(pick));
check('the menu closes on a tap outside and on Escape (focus back on More)', /document\.addEventListener\('click',e=>\{ const m=document\.getElementById\('sg-more-menu'\); if\(m&&m\.style\.display==='block'&&!m\.contains\(e\.target\)\) sgCloseMore\(\); \}\);/.test(idx)
  && /e\.key==='Escape'[\s\S]{0,200}sgCloseMore\(\); const b=document\.getElementById\('sg-more-btn'\); if\(b\) b\.focus\(\);/.test(idx));
check('the menu stays inside the row\'s gutter', /const left=Math\.max\(gutter,Math\.min\(btn\.offsetLeft-row\.scrollLeft,wrap-menu\.offsetWidth-gutter\)\);/.test(idx));

// ── 4. Markup and layout ──
const markup = idx.split('<div class="page" id="page-scout">')[1] || '';
check('markup: the league row and the More menu share a wrapper; the views row follows; the menu starts hidden (display set in JS)',
  /<div class="sg-tabs-wrap">\s*<div id="sg-tabs" class="sg-tabs"><\/div>\s*<div id="sg-more-menu" class="sg-more-menu" role="menu" style="display:none;"><\/div>\s*<\/div>\s*<div id="sg-views" class="sg-views"><\/div>\s*<div id="sg-body"><\/div>/.test(markup));
const css = (sel) => (new RegExp(sel.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\{([^}]*)\\}').exec(idx) || [])[1] || '';
check('the views row never scrolls: it wraps', /flex-wrap:wrap/.test(css('.sg-views')) && !/overflow/.test(css('.sg-views')));
check('the More menu sits outside the scrolling row, positioned under it', /position:absolute/.test(css('.sg-more-menu')) && /top:100%/.test(css('.sg-more-menu')) && /position:relative/.test(css('.sg-tabs-wrap')));
check('laptop (900px+): the league row wraps instead of scrolling', /@media \(min-width: 900px\)\{[\s\S]*?\.sg-tabs\{flex-wrap:wrap;overflow:visible;\}/.test(idx));
check('every tab and menu item is at least 44px tall', /min-height:44px/.test(css('.sg-tab')) && /min-height:44px/.test(css('.sg-more-item')));

// ── 5. Words ──
const i18n = read('public/i18n.js');
eq('EN / PT: Round · Rodada, More · Mais', [/'sg\.tab\.round': 'Round'/.test(i18n), /'sg\.tab\.round': 'Rodada'/.test(i18n), /'sg\.tab\.more': 'More'/.test(i18n), /'sg\.tab\.more': 'Mais'/.test(i18n)], [true, true, true, true]);

for (const f of failures) console.log(`  FAIL  ${f}`);
console.log(`\n${passed} passed, ${failures.length} failed`);
process.exit(failures.length ? 1 : 0);
