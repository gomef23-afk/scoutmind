// Writes the generated blocks that follow api/_lib/leagues.js, the one league
// list:
//   public/league-names.js                    between BEGIN LEAGUES / END LEAGUES
//   supabase/migrations/035_leagues_config.sql between BEGIN SEED / END SEED
//
//   node scripts/sync-leagues.mjs          rewrite both
//   node scripts/sync-leagues.mjs --check  exit 1 if either is out of date
//
// tests/leagues-config.test.js runs the check. No dependencies.

import { readFileSync, writeFileSync } from 'node:fs';
import { LEAGUES } from '../api/_lib/leagues.js';

const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');

const js = (v) => JSON.stringify(v).replace(/"/g, "'");
const sql = (v) => (v == null ? 'null' : typeof v === 'boolean' || typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

/** The browser's copy: what a page needs to name and group a league. */
export function namesBlock() {
  const rows = LEAGUES.map((l) => `    { slug: ${js(l.slug)}, name: ${js(l.name)}, country: ${js(l.country)}, code: ${js(l.code)}, region: ${js(l.region)}, playable: ${l.playable} },`);
  return ['  // BEGIN LEAGUES (generated by scripts/sync-leagues.mjs from api/_lib/leagues.js — do not edit by hand)',
    '  const LEAGUES = [', ...rows, '  ];', '  // END LEAGUES'].join('\n');
}

/** The migration's seed: one VALUES row per league. */
export function seedBlock() {
  const rows = LEAGUES.map((l) => '    (' + [l.apiId, l.slug, l.name, l.country, l.code, l.season, l.seasonStart, l.seasonEnd, l.active, l.playable, l.statsCoverage, l.region]
    .map(sql).join(', ') + ')');
  return ['-- BEGIN SEED (generated by scripts/sync-leagues.mjs from api/_lib/leagues.js — do not edit by hand)',
    'create temporary table _league_seed on commit drop as',
    'select * from (values',
    rows.join(',\n'),
    ') as s(api_league_id, slug, name, country, country_code, current_season, season_start, season_end, active, playable, stats_coverage, region);',
    '-- END SEED'].join('\n');
}

function replaceBlock(text, begin, end, block) {
  const a = text.indexOf(begin), b = text.indexOf(end);
  if (a < 0 || b < 0) throw new Error(`markers not found: ${begin} / ${end}`);
  const lineStart = text.lastIndexOf('\n', a) + 1;
  const lineEnd = text.indexOf('\n', b);
  return text.slice(0, lineStart) + block + text.slice(lineEnd < 0 ? text.length : lineEnd);
}

const targets = [
  ['public/league-names.js', 'BEGIN LEAGUES', 'END LEAGUES', namesBlock()],
  ['supabase/migrations/035_leagues_config.sql', 'BEGIN SEED', 'END SEED', seedBlock()],
];
let stale = [];
for (const [file, begin, end, block] of targets) {
  const url = new URL(file, root);
  const before = readFileSync(url, 'utf8');
  const crlf = before.includes('\r\n');
  const norm = before.replace(/\r\n/g, '\n');
  const after = replaceBlock(norm, begin, end, block);
  if (after !== norm) {
    stale.push(file);
    if (!check) writeFileSync(url, crlf ? after.replace(/\n/g, '\r\n') : after);
  }
}
if (check) {
  if (stale.length) { console.log('out of date: ' + stale.join(', ') + ' (run node scripts/sync-leagues.mjs)'); process.exit(1); }
  console.log('league blocks up to date');
} else {
  console.log(stale.length ? 'rewrote: ' + stale.join(', ') : 'league blocks already up to date');
}
