-- ---------------------------------------------------------------------------
-- 3. SCOUT GAME ROUNDS: ACTIVE AND PLAYABLE ONLY
-- ---------------------------------------------------------------------------
-- 017's function, unchanged except for `and l.playable` in the join.
create or replace function public.sync_game_rounds()
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_rounds integer;
begin
  with r as (
    select f.league_id, f.season, f.round as round_label,
           min(f.kickoff_utc) filter (where f.status_short not in ('PST','CANC','ABD','AWD','WO')) as deadline,
           count(*)           filter (where f.status_short not in ('PST','CANC','ABD','AWD','WO')) as fixture_n
      from public.fixtures f
      join public.leagues l on l.id = f.league_id and l.active and l.playable and l.current_season = f.season
     where f.round ~ ' - [0-9]+$'
     group by f.league_id, f.season, f.round
  ),
  w as (
    select r.*,
           least(
             (select min(r2.deadline) from r r2
               where r2.league_id = r.league_id and r2.season = r.season and r2.deadline > r.deadline),
             r.deadline + interval '6 days') as closes
      from r
     where r.deadline is not null
  )
  -- A round first seen after its deadline was never playable (the game did not
  -- exist yet): it starts locked, or final once its window has closed, so the
  -- lock step never has to process a backlog of empty historical rounds.
  insert into public.game_rounds as g
    (league_id, season, round_label, round_no, deadline_utc, closes_utc, fixture_count, status)
  select w.league_id, w.season, w.round_label,
         substring(w.round_label from '([0-9]+)$')::integer,
         w.deadline, coalesce(w.closes, w.deadline + interval '6 days'), w.fixture_n,
         case when coalesce(w.closes, w.deadline + interval '6 days') + interval '1 day' < now() then 'final'
              when w.deadline <= now() then 'locked'
              else 'open' end
    from w
  on conflict (league_id, season, round_label) do update set
    round_no      = excluded.round_no,
    deadline_utc  = excluded.deadline_utc,
    closes_utc    = excluded.closes_utc,
    fixture_count = excluded.fixture_count,
    updated_at    = now()
  where g.status = 'open';
  get diagnostics v_rounds = row_count;

  -- Every round gets its fixture rows (historical ones too: the backtest scores
  -- them); only rounds that are not final keep updating their flags.
  insert into public.game_round_fixtures (round_id, fixture_id, counts)
  select g.id, f.id,
         (f.status_short not in ('PST','CANC','ABD','AWD','WO')
          and f.kickoff_utc >= g.deadline_utc and f.kickoff_utc < g.closes_utc)
    from public.game_rounds g
    join public.fixtures f
      on f.league_id = g.league_id and f.season = g.season and f.round = g.round_label
  on conflict (round_id, fixture_id) do nothing;

  update public.game_round_fixtures gf
     set counts = x.counts
    from (
      select g.id as round_id, f.id as fixture_id,
             (f.status_short not in ('PST','CANC','ABD','AWD','WO')
              and f.kickoff_utc >= g.deadline_utc and f.kickoff_utc < g.closes_utc) as counts
        from public.game_rounds g
        join public.fixtures f
          on f.league_id = g.league_id and f.season = g.season and f.round = g.round_label
       where g.status <> 'final'
    ) x
   where gf.round_id = x.round_id and gf.fixture_id = x.fixture_id
     and gf.counts is distinct from x.counts;

  return v_rounds;
end;
$$;

revoke all on function public.sync_game_rounds() from public, anon, authenticated;
grant execute on function public.sync_game_rounds() to service_role;

-- ---------------------------------------------------------------------------
-- 4. A ROOM FOR EVERY CLUB
-- ---------------------------------------------------------------------------
-- The same room and welcome 011 and 033 created, for a club inserted later.
-- Runs as the owner (groups and system messages are not writable by users);
-- the insert guard on group_messages lets system rows through (028b).
create or replace function public.ensure_club_room()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_group uuid;   -- groups.id is a uuid (011), like 019's v_room. It was bigint here until 035b.
begin
  select g.id into v_group from public.groups g where g.club_id = new.id and g.is_official limit 1;
  if v_group is null then
    insert into public.groups (club_id, name, description, is_official, active)
    values (new.id, new.name || ' Community',
            'Match days, transfers, arguments. The official ' || new.name || ' room.', true, true)
    returning id into v_group;
  end if;
  if not exists (select 1 from public.group_messages m
                  where m.group_id = v_group and m.is_system and m.pinned and m.deleted_at is null) then
    insert into public.group_messages (group_id, user_id, content, pinned, is_system)
    values (v_group, null,
            'Bem-vindos à sala oficial da torcida: ' || new.name
              || '. Dia de jogo, mercado, discussão. Respeito sempre.'
              || ' · Welcome to the official ' || new.name
              || ' room. Match days, transfers, arguments. Be decent.',
            true, true);
  end if;
  return new;
end;
$$;

revoke all on function public.ensure_club_room() from public, anon, authenticated;

drop trigger if exists teams_ensure_club_room on public.teams;
create trigger teams_ensure_club_room
  after insert on public.teams
  for each row execute function public.ensure_club_room();

-- Backfill: clubs of active leagues without a room, then rooms without a welcome.
insert into public.groups (club_id, name, description, is_official, active)
select t.id, t.name || ' Community',
       'Match days, transfers, arguments. The official ' || t.name || ' room.', true, true
  from public.teams t
  join public.leagues l on l.id = t.league_id and l.active
 where not exists (select 1 from public.groups g where g.club_id = t.id and g.is_official);

insert into public.group_messages (group_id, user_id, content, pinned, is_system)
select g.id, null,
       'Bem-vindos à sala oficial da torcida: ' || t.name
         || '. Dia de jogo, mercado, discussão. Respeito sempre.'
         || ' · Welcome to the official ' || t.name
         || ' room. Match days, transfers, arguments. Be decent.',
       true, true
  from public.groups g
  join public.teams t on t.id = g.club_id
 where g.is_official
   and not exists (select 1 from public.group_messages m
                    where m.group_id = g.id and m.is_system and m.pinned and m.deleted_at is null);

commit;

