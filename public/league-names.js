// League names with the country code, everywhere a league is named
// (Sequence 2 commit 4b, decision of 17 Nov 2026): "Série A · BRA",
// "Serie A · ITA". Flags are emoji and the spec rules emoji out, and several
// of our leagues read alike without the country (Série A/B/C · BRA and
// Serie A · ITA; Premier League · ENG and Premiership · SCO), so the code is
// always there. Codes are FIFA-style and the same in every language.
//
// The list below is GENERATED from api/_lib/leagues.js, the one league list
// (node scripts/sync-leagues.mjs); tests/leagues-config.test.js fails if it
// drifts. Never edit it by hand.
//
// LeagueNames.label(x) takes whatever the caller holds:
//   - a slug ('serie_a_it'), or a league's exact name ('Série A');
//   - an object with any of { slug, name, country, country_code } (a leagues
//     row, an embed).
// The code comes from the object's country_code, else from the league list
// (by slug, then by name AND country, then by a name only one league has),
// else from the country; an international competition has none.
// Pure: no DOM, no network. Pinned by tests/league-names.test.js. Precached
// (rule 24).
(function (root) {
  'use strict';

  // BEGIN LEAGUES (generated by scripts/sync-leagues.mjs from api/_lib/leagues.js — do not edit by hand)
  const LEAGUES = [
    { slug: 'serie_a', name: 'Série A', country: 'Brazil', code: 'BRA', region: 'brazil', playable: true },
    { slug: 'premier_league', name: 'Premier League', country: 'England', code: 'ENG', region: 'europe', playable: true },
    { slug: 'la_liga', name: 'La Liga', country: 'Spain', code: 'ESP', region: 'europe', playable: true },
    { slug: 'bundesliga', name: 'Bundesliga', country: 'Germany', code: 'GER', region: 'europe', playable: true },
    { slug: 'serie_a_it', name: 'Serie A', country: 'Italy', code: 'ITA', region: 'europe', playable: true },
    { slug: 'ligue_1', name: 'Ligue 1', country: 'France', code: 'FRA', region: 'europe', playable: true },
    { slug: 'argentina', name: 'Liga Profesional', country: 'Argentina', code: 'ARG', region: null, playable: true },
    { slug: 'championship', name: 'Championship', country: 'England', code: 'ENG', region: 'europe', playable: false },
    { slug: 'eredivisie', name: 'Eredivisie', country: 'Netherlands', code: 'NED', region: 'europe', playable: false },
    { slug: 'primeira_liga', name: 'Primeira Liga', country: 'Portugal', code: 'POR', region: 'europe', playable: false },
    { slug: 'belgian_pro_league', name: 'Jupiler Pro League', country: 'Belgium', code: 'BEL', region: 'europe', playable: false },
    { slug: 'scottish_premiership', name: 'Premiership', country: 'Scotland', code: 'SCO', region: 'europe', playable: false },
    { slug: 'super_lig', name: 'Süper Lig', country: 'Turkey', code: 'TUR', region: 'europe', playable: false },
    { slug: 'saudi_pro_league', name: 'Saudi Pro League', country: 'Saudi Arabia', code: 'KSA', region: null, playable: false },
    { slug: 'mls', name: 'MLS', country: 'USA', code: 'USA', region: null, playable: false },
    { slug: 'liga_mx', name: 'Liga MX', country: 'Mexico', code: 'MEX', region: null, playable: false },
    { slug: 'serie_b', name: 'Série B', country: 'Brazil', code: 'BRA', region: 'brazil', playable: false },
    { slug: 'serie_c', name: 'Série C', country: 'Brazil', code: 'BRA', region: 'brazil', playable: false },
    { slug: 'uruguay', name: 'Primera División', country: 'Uruguay', code: 'URU', region: null, playable: false },
  ];
  // END LEAGUES

  /** Country → code, from the list (for an object that carries a country only). */
  const COUNTRY_CODE = {};
  LEAGUES.forEach((l) => { if (l.country && !COUNTRY_CODE[l.country]) COUNTRY_CODE[l.country] = l.code; });
  COUNTRY_CODE['Saudi-Arabia'] = 'KSA';   // API-Football's spelling

  /** One of LEAGUES: by slug; by name and country; by a name only one league has. */
  function find(x) {
    if (!x) return null;
    const byName = (n) => { const m = LEAGUES.filter((l) => l.name === n); return m.length === 1 ? m[0] : null; };
    if (typeof x === 'string') return LEAGUES.find((l) => l.slug === x) || byName(x);
    return (x.slug && LEAGUES.find((l) => l.slug === x.slug))
      || (x.name && x.country && LEAGUES.find((l) => l.name === x.name && l.country === x.country))
      || (x.name && byName(x.name)) || null;
  }

  /** The country code, or '' when there is no country. */
  function code(x) {
    if (x && typeof x === 'object' && x.country_code) return String(x.country_code);
    const known = find(x);
    if (known) return known.code;
    const country = (x && typeof x === 'object' && x.country) || '';
    if (!country) return '';
    return COUNTRY_CODE[country] || String(country).slice(0, 3).toUpperCase();
  }

  /** The league's name, plain (no code). */
  function name(x) {
    if (!x) return '';
    const known = find(x);
    if (typeof x === 'object') return x.name || (known && known.name) || '';
    return known ? known.name : x;
  }

  /** "Série A · BRA"; the name alone when there is no country; '' for nothing. */
  function label(x) {
    const n = name(x);
    if (!n) return '';
    const c = code(x);
    return c ? n + ' · ' + c : n;
  }

  /** The news region ('brazil' | 'europe' | null). */
  function region(x) { const k = find(x); return k ? k.region : null; }

  /** In the Scout Game. A league we do not list is not. */
  function playable(x) {
    if (x && typeof x === 'object' && typeof x.playable === 'boolean') return x.playable;
    const k = find(x); return !!(k && k.playable);
  }

  /**
   * The order every league list uses (chips, pickers, club lists): the
   * reader's leagues first, then alphabetical by label. items: slugs or
   * objects; mine: a Set (or array) of slugs.
   */
  function sort(items, mine) {
    const m = mine instanceof Set ? mine : new Set(mine || []);
    const slugOf = (x) => (typeof x === 'string' ? x : (x && (x.slug || (find(x) || {}).slug)) || '');
    return (items || []).slice().sort((a, b) => (m.has(slugOf(b)) - m.has(slugOf(a)))
      || label(a).localeCompare(label(b), undefined, { sensitivity: 'base' }));
  }

  root.LeagueNames = { label, name, code, find, region, playable, sort, LEAGUES, COUNTRY_CODE };
})(typeof window !== 'undefined' ? window : globalThis);
